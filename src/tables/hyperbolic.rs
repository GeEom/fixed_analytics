/// Whether hyperbolic CORDIC must repeat iteration `index` to converge: 4, 13,
/// 40, 121, 364, each term three times the last plus one.
#[inline]
#[must_use]
pub const fn needs_repeat(index: u32) -> bool {
    matches!(index, 4 | 13 | 40 | 121 | 364)
}

